import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={};context.globalThis=context;context.window=context;vm.createContext(context);
vm.runInContext(fs.readFileSync('v0.1/chatcore.js','utf8'),context);
vm.runInContext(fs.readFileSync('demo/scenario-dhcp.js','utf8'),context);
const core=context.ChatCore;
assert.equal(core.version,'0.1.0');
const sample=context.ChatCoreDemo;
let chat=core.create(sample),seen=0;
const unsubscribe=chat.subscribe(()=>seen++);
assert.equal(chat.getState().history.length,1,'Accueil de Sophie');
assert.equal(chat.getState().history[0].role,'client');
assert.ok(chat.available().some(x=>x.id==='scope'));
assert.equal(chat.send('nonexistent'),false);
assert.equal(chat.send('scope'),true);
assert.equal(chat.getState().history[1].role,'me');
assert.equal(chat.getState().history[2].role,'client');
assert.match(chat.getState().history[2].text,/VLAN 30/);
assert.ok(!chat.available().some(x=>x.id==='scope'),'Question déjà posée retirée');
assert.equal(chat.send('scope'),false);
assert.equal(chat.send('check'),true);
assert.match(chat.getState().history.at(-1).text,/toujours pas/);
const before=chat.getState().history.length;
chat.notify({type:'dhcp.lease-restored'});
assert.equal(chat.getState().facts.networkRestored,true);
assert.equal(chat.getState().history.length,before,'Événement conservant le dialogue');
assert.equal(chat.send('check'),true,'Question de vérification répétable');
assert.match(chat.getState().history.at(-1).text,/fonctionne à nouveau/);
assert.equal(chat.getState().history.length,before+2);
assert.ok(seen>=5);
unsubscribe();
chat.restart();
assert.equal(chat.getState().history.length,1);
assert.equal(chat.getState().facts.networkRestored,false,'Réinitialisation du simulateur');
assert.equal(chat.available().length,sample.messages.length);
assert.throws(()=>core.create({messages:[{id:'x',text:'x',answer:'ok'},{id:'x',text:'y',answer:'ok'}]}),/dupliqué/);
assert.throws(()=>chat.notify({}),/événement invalide/);
console.log('OK : 17 assertions ChatCore (dialogue, état, événements, répétition, historique, réinitialisation).');

const css=fs.readFileSync('v0.1/chatcore.css','utf8');
const demo=fs.readFileSync('index.html','utf8');
for(const theme of ['pure','dark','neon','space','80']){
 assert.ok(css.includes('html[data-ctp-theme="'+theme+'"] .chatcore'),'Compatibilité C² '+theme);
 assert.ok(demo.includes('<option value="'+theme+'">'),'Prévisualisation '+theme);
}
assert.match(css,/var\(--ctp-panel/,'Héritage des couleurs du conteneur C²');
assert.match(css,/var\(--ctp-accent/,'Héritage de la couleur d’accent C²');
assert.match(css,/\.chatcore \.cc-client/,'Bulles client distinctes');
assert.match(css,/\.chatcore \.cc-me/,'Bulles technicien distinctes');
assert.match(demo,/themeTest\.addEventListener\('change'/,'Changement de thème sans rechargement');
console.log('OK : les cinq thèmes de C² sont couverts sans modifier le moteur conversationnel.');
